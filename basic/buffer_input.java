import java.util.Scanner;

public class buffer_input {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        // 1. Reading an integer
        System.out.print("Enter your age: ");
        int age = scanner.nextInt(); 
        // If you type "25" and press Enter, the buffer contains: [25][\n]
        // nextInt() grabs 25, leaving [\n] inside the buffer.

        // ❌ THE FIX: Consume the leftover newline character from the buffer
        scanner.nextLine(); 

        // 2. Reading a string
        System.out.print("Enter your name: ");
        String name = scanner.nextLine(); 
        // If we hadn't cleared the buffer above, this line would instantly 
        // grab the leftover [\n], look empty, and skip your typing entirely!

        System.out.println("Hello " + name + ", you are " + age + " years old.");
        scanner.close();
    
}
}/** 
 What you type vs. What goes into the buffer

When the program asks for input and you type 25 and hit Enter, your keyboard sends three distinct characters into the input buffer:
• Character 1: '2'
• Character 2: '5'
• Character 3: '\n' (The newline character generated by the Enter key)
At this point, the buffer looks like this: [ 2 ][ 5 ][ \n ]

2. How nextInt() behaves

When scanner.nextInt() executes, it scans the buffer looking specifically for digits to turn into an integer:
1. It sees '2' and '5', groups them together, and converts them to the integer 25.
2. It stops reading the exact moment it hits a non-digit character (which is the \n).
3. It leaves that \n sitting untouched inside the buffer.
The buffer now looks like this: [ \n ]

3. Why nextLine() gets tripped up

Right after, when you call scanner.nextLine(), its job is to read everything up until the very next \n character.
1. It looks at the buffer and immediately sees [ \n ] left behind from your previous keystroke.
2. It says, "Oh, look! A newline character! The user must have already pressed Enter."
3. It consumes the \n, removes it from the buffer, and returns a blank string "" before you even get a chance to type anything.*/