public class switch_constant {
    public static void main(String[] args) {
        int x = 10; 
        final int y = 20; 
        switch (x) 
        { 
        case 10: 
            System.out.println("Neostark"); 
            break; 
        case y: 
            System.out.println("Neowise"); 
            break; 
        }
	}
    
}
